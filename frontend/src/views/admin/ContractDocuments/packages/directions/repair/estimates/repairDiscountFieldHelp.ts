export type RepairDiscountFieldHelpContext = {
  isWindowsPackage: boolean;
  contractLocked: boolean;
};

export function repairDiscountFieldHelp({
  isWindowsPackage,
  contractLocked,
}: RepairDiscountFieldHelpContext): {
  title: string;
  steps: readonly string[];
  note?: string;
} {
  const estimateLabel = isWindowsPackage ? '«Счёт-заказ»' : '«Смета»';
  const estimateShort = isWindowsPackage ? 'счёта-заказа' : 'сметы';

  if (contractLocked) {
    return {
      title: 'Скидка по договору',
      steps: [
        'Процент скидки (от 0 до 100), заданный до подписания договора.',
        'Договор подписан (или отмечен как отказ) — изменить скидку нельзя.',
        `Используется в печатных документах, на вкладке ${estimateLabel}, в доп. соглашениях, заказ-нарядах и «Оплаты».`,
        'В шаблоне: {{contract.discountPercent}}.',
      ],
      note: 'Итоговые суммы со скидкой уже зафиксированы в пакете договора.',
    };
  }

  return {
    title: 'Скидка по договору',
    steps: [
      'Процент скидки от 0 до 100. Пустое поле или 0 — без скидки.',
      `Применяется ко всему договору: итоги ${estimateShort}, доп. соглашения, заказ-наряды (позиции со скидкой), вкладка «Оплаты».`,
      isWindowsPackage
        ? 'На вкладке «Данные» пересчитывается «Стоимость работ» (из счёта-заказа со скидкой) и общая стоимость договора.'
        : 'На вкладке «Данные» пересчитывается «Стоимость договора» из сметы с учётом скидки (поле только для чтения).',
      `В таблице на вкладке ${estimateLabel} суммы по строкам — без скидки; скидка показана в итоговом блоке («Итого со скидкой»).`,
      'После изменения скидки проверьте итоги на вкладке «Оплаты» и при необходимости скорректируйте оплату.',
      'В шаблоне: {{contract.discountPercent}}.',
    ],
    note: 'До подписания договора скидку может менять любой пользователь с доступом к редактированию пакета.',
  };
}
