/** Общие абзацы про дистанционное подписание (ПЭП) для шаблонов индивидуальных договоров. */

const PARAGRAPH_STYLE =
  'text-align: justify; text-indent: 1.25cm; margin: 0 0 6pt; line-height: 1.32';

function clauseParagraph(number: string, html: string): string {
  return `<p style="${PARAGRAPH_STYLE}" data-contract-paragraph-spacing="normal">${number} ${html}</p>`;
}

/** Пункты 8.4–8.11 (или 8.3–8.10, если мессенджеры вынесены отдельно) — вставлять после п. про мессенджеры. */
export function buildContractRemoteSigningClausesHtml(options?: {
  /** Первая нумерация блока (по умолчанию 8.4). */
  startNumber?: number;
  /** «Исполнитель» или «Подрядчик». */
  contractorLabel?: 'Исполнитель' | 'Подрядчик';
}): string {
  const start = options?.startNumber ?? 8.4;
  const contractor = options?.contractorLabel ?? 'Исполнитель';
  const n = (offset: number) => {
    const major = Math.floor(start);
    const minorStart = Math.round((start - major + Number.EPSILON) * 10);
    return `${major}.${minorStart + offset}.`;
  };

  return [
    clauseParagraph(
      n(0),
      `<strong>Простая электронная подпись (ПЭП)</strong> — подпись Заказчика, формируемая путём открытия персональной ссылки на Сайте https://territory-interior.ru/, ознакомления с Электронными документами, ввода фамилии, имени и отчества (при необходимости — иных идентификационных данных) и одноразового кода подтверждения, переданного ${contractor}ом, а также подтверждения согласия с условиями документов.`
    ),
    clauseParagraph(
      n(1),
      `<strong>Электронный документ</strong> — документ в электронной форме (в том числе PDF), доступный по ссылке на Сайте и/или направленный по электронной почте либо через мессенджер.`
    ),
    clauseParagraph(
      n(2),
      `${contractor} вправе направлять Заказчику настоящий Договор, приложения к нему, акты и иные документы по Заказу в виде Электронных документов: по адресу электронной почты {{customer.email|plain}}; через мессенджеры (WhatsApp, Telegram, MAX и иные) по телефону {{customer.phone|plain}}; посредством персональной ссылки на Сайте.`
    ),
    clauseParagraph(
      n(3),
      'Заказчик обязуется самостоятельно ознакомиться с направленными Электронными документами до их подписания.'
    ),
    clauseParagraph(
      n(4),
      `Подписание настоящего Договора, приложений и актов может осуществляться простой электронной подписью: Заказчик открывает персональную ссылку на Сайте, просматривает документы, вводит ФИО и одноразовый код подтверждения, полученный от ${contractor}а, и подтверждает согласие с условиями документов в представленном виде.`
    ),
    clauseParagraph(
      n(5),
      `Совершение действий, указанных в предыдущем пункте, признаётся подписанием соответствующих Электронных документов Заказчиком и выражением его воли заключить (изменить) обязательства на условиях этих документов. Моментом подписания считается успешное подтверждение на Сайте. ${contractor} вправе фиксировать в информационной системе дату и время подписания, ФИО подписанта и состав документов.`
    ),
    clauseParagraph(
      n(6),
      'Персональная ссылка и одноразовый код могут быть ограничены сроком действия. ' +
        `${contractor} вправе отозвать ссылку до момента подписания. При истечении срока или отзыве ссылки подписание по ней невозможно.`
    ),
    clauseParagraph(
      n(7),
      'Отказ Заказчика от подписания через Сайт (в том числе с указанием причины) не исключает последующего подписания на бумажном носителе либо иным согласованным способом.'
    ),
    clauseParagraph(
      n(8),
      'Обработка персональных данных (в том числе телефона и адреса электронной почты) для направления ссылки, кода и документов осуществляется в соответствии с Политикой обработки персональных данных, размещённой на Сайте.'
    ),
  ].join('\n  ');
}

/** Абзац про мессенджеры (единый для всех направлений). */
export function buildContractMessengerClauseHtml(clauseNumber: string): string {
  return clauseParagraph(
    `${clauseNumber}`,
    'Переписка в мессенджерах (WhatsApp, Telegram, MAX и иные) по номерам телефонов, указанным в договоре, а также направление Электронных документов и одноразового кода подтверждения указанными способами имеют юридическую силу для уведомлений, согласований и подписания в порядке настоящего раздела.'
  );
}

/** Дополнение для договора ремонта (вариант A оферты): акт начала работ через ПЭП. */
export function buildRepairActStartPepClauseHtml(clauseNumber: string): string {
  return clauseParagraph(
    `${clauseNumber}`,
    'Акт начала работ (Приложение № 2) может подписываться на бумажном носителе либо простой электронной подписью в порядке настоящего раздела, если Акт направлен Заказчику как Электронный документ.'
  );
}
