export type RepairContractDateFieldHelpContext = {
  contractLocked: boolean;
  isWindowsPackage: boolean;
};

export function repairContractDateFieldHelp({
  contractLocked,
  isWindowsPackage,
}: RepairContractDateFieldHelpContext): {
  title: string;
  steps: readonly string[];
  note?: string;
} {
  const estimateLabel = isWindowsPackage ? '«Счёт-заказ»' : '«Смета»';

  if (contractLocked) {
    return {
      title: 'Дата заключения договора',
      steps: [
        'Дата заключения договора в формате дд.мм.гггг (например, 15.03.2026).',
        'Договор подписан (или отмечен как отказ) — изменить дату нельзя.',
        'Используется в тексте договора, доп. соглашениях, приложениях к смете и других документах пакета.',
        'В шаблоне: {{contract.date}}.',
      ],
      note: 'В заголовках печати фигурирует как «от …» рядом с номером договора.',
    };
  }

  return {
    title: 'Дата заключения договора',
    steps: [
      'Дата заключения договора в формате дд.мм.гггг (день.месяц.год).',
      'Если поле пустое при первом сохранении пакета, подставится сегодняшняя дата.',
      'Допускается ввод с точками; при загрузке старых данных возможны форматы гггг-мм-дд или дд-мм-гггг — они приводятся к дд.мм.гггг.',
      'Отображается в шапке договора, в ссылках «договор № … от …» на вкладках документов и в приложении к ' +
        estimateLabel +
        '.',
      'Влияет на дату в доп. соглашениях и в реквизитах счетов, где дата берётся из пакета.',
      'В шаблоне: {{contract.date}}.',
    ],
    note: 'До подписания договора дату может менять любой пользователь с доступом к редактированию пакета.',
  };
}
