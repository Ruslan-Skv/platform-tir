/** Статусы замера в UI (форма, список, журнал). */
export const MEASUREMENT_STATUS_OPTIONS = [
  { value: 'NEW', label: 'Новый' },
  { value: 'COMPLETED', label: 'Выполнен' },
  { value: 'CANCELLED', label: 'Отказ' },
  { value: 'CONVERTED', label: 'Договор' },
] as const;

export const MEASUREMENT_STATUS_LABELS: Record<string, string> = {
  NEW: 'Новый',
  ASSIGNED: 'Назначен',
  IN_PROGRESS: 'В работе',
  COMPLETED: 'Выполнен',
  CANCELLED: 'Отказ',
  CONVERTED: 'Договор',
};

export function getMeasurementStatusLabel(status: string): string {
  return MEASUREMENT_STATUS_LABELS[status] ?? status;
}

/** Подсказка к полю «Статус» на карточке замера. */
export function buildMeasurementStatusFieldHint(opts?: { hasLinkedEstimate?: boolean }): string {
  const parts = [
    'Статусы в списке:',
    '• Новый — замер принят; результаты по направлениям ещё не завершены (или фиксация снята).',
    '• Выполнен — замер завершён по всем выбранным направлениям.',
    '• Отказ — отказ клиента или прекращение работы по замеру.',
    '• Договор — по замеру оформлен договор (обычно вручную, когда пакет документов готов).',
    '',
    'Автоматика (блок «Результаты замеров»):',
    '• «Выполнен» ставится сам после «Зафиксировать вкладку» на каждой видимой вкладке направления.',
    '• При «Отменить фиксацию вкладки» хотя бы на одной вкладке «Выполнен» сбрасывается на «Новый».',
    '• Для «Отказ» и «Договор» вкладки статус не меняют.',
    '',
    'Ручная смена в этом списке применяется после «Сохранить замер» вверху страницы. ' +
      'С «Выполнен» на «Новый» можно перейти вручную; ' +
      'если все вкладки направлений по-прежнему зафиксированы, при следующей фиксации вкладки статус снова станет «Выполнен».',
  ];

  if (opts?.hasLinkedEstimate) {
    parts.push(
      '',
      'По этому замеру уже создан расчёт: это не блокирует смену статуса здесь. ' +
        'Статус замера и данные расчёта связаны только по смыслу процесса, не технически.'
    );
  } else {
    parts.push('', 'Наличие расчёта по замеру не запрещает менять статус в этом поле.');
  }

  return parts.join('\n');
}
